import React, { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { feeInfo } from '../../api/_shingi/fee';
import { OFFER_EDITION_LABEL } from '../../api/_shingi/offer';
import { fmtDate, fmtMoney, sg } from './api';
import { Card, H2, Shell, display, usePageSetup } from './ui';

/**
 * Реквізити організатора для оферти. Юридичну назву, код і рахунок заповнюйте тут — поки поля порожні, рядки на сторінці не показуються.
 * Нічого вигаданого сюди не підставляємо.
 */
const ORGANIZER_LEGAL = {
  name: '', // наприклад: ФОП Прізвище Ім'я По батькові
  taxId: '', // РНОКПП / код ЄДРПОУ
  iban: '',
};

const ORGANIZER = {
  brand: 'Black Bear Dojo',
  contact: 'Котляревський Ігор',
  address: "Київ, вул. Сім'ї Бродських, 31/33",
  phone: '095 475 65 00',
  telegram: '@ihorkot',
};

const EDITION = OFFER_EDITION_LABEL;

const capitalize = (text: string) => (text ? text[0].toUpperCase() + text.slice(1) : text);

const P = ({ children }: { children: React.ReactNode }) => <p className="mt-3 text-[15px] leading-relaxed text-[#cfcfca]">{children}</p>;

export default function OfferPage() {
  usePageSetup('Публічна оферта');
  const [params] = useSearchParams();
  const eventId = Number(params.get('event')) > 0 ? Number(params.get('event')) : null;
  const [event, setEvent] = useState<any | null>(null);
  const [loaded, setLoaded] = useState(false);

  // оферта на кожен івент: ?event=<id> — умови цього заходу, без параметра — активного
  useEffect(() => {
    sg<{ event: any | null }>(`event/current${eventId ? `?event_id=${eventId}` : ''}`)
      .then((r) => setEvent(r.event))
      .catch(() => undefined)
      .finally(() => setLoaded(true));
  }, [eventId]);

  const info = feeInfo({ fee_uah: event?.fee_uah ?? 0, fee_kind: event?.fee_kind, fee_label: event?.fee_label });
  const known = Boolean(event);
  const free = known && info.free;
  const fee = info.amount_uah;
  const charity = info.kind === 'charity';
  const title = event?.title || 'SHIN GI · Kyokushin Open';
  const date = event?.event_date ? fmtDate(event.event_date) : 'за оголошеною датою';
  const place = event?.address || `${ORGANIZER.address}, зал ${ORGANIZER.brand}`;

  return (
    <Shell right={<a href="/shin-gi" className={`${display} text-[12px] text-[#85857f] hover:text-[#C9A227]`}>← SHIN GI</a>}>
      <Card className="!p-5 sm:!p-8">
        <p className={`${display} flex items-center gap-3 text-[12px] text-[#C9A227]`}>
          <span className="h-[2px] w-9 bg-[#A3101A]" />
          Редакція від {EDITION}
        </p>
        <h1 className={`${display} mt-3 text-[34px] font-bold leading-[1.05] sm:text-[52px]`}>
          Публічна оферта <br />
          <span className="text-[#A3101A]">про участь у SHIN GI</span>
        </h1>
        <P>
          Цей документ є публічною пропозицією (офертою) укласти договір про надання послуг з організації та участі у спортивному заході
          відповідно до статей 633, 641 і 642 Цивільного кодексу України. {free
            ? 'Договір вважається укладеним з моменту, коли Замовник подав заявку на участь у заході.'
            : 'Договір вважається укладеним з моменту, коли Замовник поставив відмітку згоди з офертою в кабінеті та здійснив оплату (картка або готівка).'}
        </P>
        {known && <P>Захід: <b>«{title}»</b>, {date}. Умови цієї редакції стосуються саме цього заходу.</P>}
      </Card>

      <Card>
        <H2 n="1">Терміни</H2>
        <P><b>Організатор</b> — {ORGANIZER.brand}{ORGANIZER_LEGAL.name ? `, ${ORGANIZER_LEGAL.name}` : ''}.</P>
        <P><b>Замовник</b> — особа (тренер, боєць або законний представник неповнолітнього бійця), яка подає заявку й оплачує участь.</P>
        <P><b>Боєць</b> — учасник заходу, за якого подано заявку. <b>Кабінет</b> — особистий кабінет на сайті shin-karate.kyiv.ua/shin-gi.</P>
      </Card>

      <Card>
        <H2 n="2">Предмет договору</H2>
        <P>
          Організатор проводить спаринг-день «{title}» ({date}, {place}) і надає Бійцю право взяти в ньому участь у відповідному блоці (Kids або Open).
          Групи формуються за статтю, віком, вагою і поясом. Кожному учаснику вручається медаль і грамота.
        </P>
        <P>
          Організатор має право об'єднувати, розділяти й переміщувати групи, змінювати розклад і регламент для проведення заходу, повідомляючи про це
          тренерів у кабінеті або через бота.
        </P>
      </Card>

      <Card>
        <H2 n="3">{free ? 'Участь і оплата' : 'Вартість і порядок оплати'}</H2>
        {free ? (
          <P>
            Участь у цьому заході <b>безкоштовна</b>. Оплата не передбачена, тому положення цієї оферти про оплату карткою, комісію банку та повернення коштів не застосовуються.
            Договір вважається укладеним з моменту подання заявки.
          </P>
        ) : (
          <>
            <P>
              {capitalize(info.noun)} за участь одного Бійця —{' '}
              <b>{known ? fmtMoney(fee) : 'сума вказана в кабінеті'}</b>. Оплата здійснюється до дедлайну, зазначеного в кабінеті.
              {charity && ' Благодійний внесок спрямовується на цілі, які Організатор оголосив в описі заходу.'}
              {info.kind === 'custom' && ` Призначення платежу: «${info.noun}».`}
            </P>
            <P>
              <b>Оплата карткою</b> проводиться онлайн через платіжний сервіс банку-еквайра (monobank). Комісію банку за онлайн-оплату сплачує Замовник: сума
              до сплати карткою дорівнює внеску плюс комісія банку. Розмір комісії та загальну суму Замовник бачить у кабінеті до оплати й у платіжній
              формі; вона не є доходом Організатора і покриває лише вартість еквайрингу.
            </P>
            <P><b>Оплата готівкою</b> можлива безпосередньо Організатору без комісії. Організатор вносить відмітку про оплату в системі, після чого статус заявки змінюється на «Оплачено».</P>
            <P>Дані банківської картки Організатору не передаються і ним не зберігаються: їх обробляє платіжний сервіс банку.</P>
          </>
        )}
      </Card>

      <Card>
        <H2 n="4">Права й обов'язки сторін</H2>
        <P>Замовник зобов'язується: вказувати достовірні дані Бійця (прізвище та ім'я, вік або дату народження, вагу, пояс); дотримуватися регламенту та вимог безпеки заходу; сплатити внесок у встановлений строк.</P>
        <P>
          Замовник відповідає за стан здоров'я Бійців і за наявність дозволу або згоди законних представників неповнолітніх учасників. Організатор має право
          не допустити Бійця до участі, якщо вказані дані суттєво відрізняються від фактичних (зокрема вага або пояс), або з міркувань безпеки.
        </P>
        <P>Організатор зобов'язується провести захід, забезпечити суддівство, медичну допомогу та вручити нагороди кожному учаснику.</P>
      </Card>

      <Card>
        <H2 n="5">Повернення коштів</H2>
        {free ? (
          <P>Оскільки участь безкоштовна, кошти не сплачуються й не повертаються. Якщо захід скасовано, Організатор повідомляє про це тренерів у кабінеті або через бота.</P>
        ) : (
          <>
            <P>Якщо захід скасовано з вини Організатора, Замовнику повертається повна сума, сплачена за участь, включно з комісією банку.</P>
            <P>
              {charity
                ? 'Благодійний внесок після проведення заходу не повертається. До цього повернення можливе лише у випадку, погодженому з Організатором письмово.'
                : 'Якщо Замовник відмовляється від участі Бійця до дедлайну внеску, повертається внесок за цього Бійця; комісія банку, утримана платіжним сервісом, не повертається, якщо інше не передбачено банком. Після дедлайну внеску кошти не повертаються, окрім випадків скасування заходу або іншого, погодженого з Організатором письмово.'}
            </P>
            <P>Повернення здійснюється тим самим способом, яким проведено оплату. Для запиту на повернення зверніться до Організатора за контактами нижче.</P>
          </>
        )}
      </Card>

      <Card>
        <H2 n="6">Персональні дані</H2>
        <P>
          Для участі обробляються дані Замовника і Бійця: прізвище та ім'я, вік або дата народження, вага, пояс, клуб, контактний телефон і обліковий запис Telegram.
          Дані використовуються лише для організації й проведення заходу, формування груп, зв'язку та обліку оплат. Подаючи заявку, Замовник підтверджує,
          що має право передати ці дані (зокрема даних неповнолітніх) і погоджується на їх обробку.
        </P>
      </Card>

      <Card>
        <H2 n="7">Форс-мажор і відповідальність</H2>
        <P>
          Сторони звільняються від відповідальності за невиконання зобов'язань, якщо воно спричинене обставинами непереборної сили (військові дії, повітряні
          тривоги, що унеможливлюють проведення заходу, рішення органів влади, аварії в мережах тощо). У такому разі захід переноситься або скасовується
          за правилами розділу 5.
        </P>
        <P>Спори вирішуються шляхом переговорів, а за недосягнення згоди — в суді за законодавством України.</P>
      </Card>

      <Card>
        <H2 n="8">Строк дії та реквізити Організатора</H2>
        <P>Оферта діє до завершення заходу й виконання сторонами зобов'язань. Організатор може змінювати оферту; зміни не поширюються на вже укладені договори.</P>
        <div className="mt-3 space-y-1 text-[15px] text-[#cfcfca]">
          <p><b>Організатор:</b> {ORGANIZER_LEGAL.name || ORGANIZER.brand}</p>
          {ORGANIZER_LEGAL.taxId && <p><b>Код:</b> {ORGANIZER_LEGAL.taxId}</p>}
          {ORGANIZER_LEGAL.iban && <p><b>IBAN:</b> {ORGANIZER_LEGAL.iban}</p>}
          <p><b>Контактна особа:</b> {ORGANIZER.contact}</p>
          <p><b>Адреса:</b> {ORGANIZER.address}</p>
          <p><b>Телефон:</b> <a className="text-[#C9A227] underline" href={`tel:+38${ORGANIZER.phone.replace(/\s/g, '')}`}>{ORGANIZER.phone}</a></p>
          <p><b>Telegram:</b> <a className="text-[#C9A227] underline" href={`https://t.me/${ORGANIZER.telegram.slice(1)}`}>{ORGANIZER.telegram}</a></p>
        </div>
      </Card>
    </Shell>
  );
}
